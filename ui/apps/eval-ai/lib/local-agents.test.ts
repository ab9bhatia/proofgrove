import { describe, expect, it } from "vitest";
import type { AgentSummary, TargetVersion } from "@/lib/api";
import { NOVA_AGENT_DEMO, NOVA_AGENT_EVALUATION_HREF, nameAfterAgentChange, agentEvaluationHref, isLocalWorkflowAgent, localAgentStrings, runnableAgentMetricIds } from "./local-agents";

const target: TargetVersion = {
  target_version_id: "nova-v1", project_id: "local-project", tenant_id: "local-tenant", name: "Nova refunds", version: "1", endpoint: "local:nova-refunds", target_type: "agent", environment: "local", tool_versions: {},
  target_id: "stored-target-id",
  configuration: { catalog_source: "local_workflow", agent_ref: "local:nova-refunds", recommended_dataset_id: "agent_nova_refunds_v1" },
};

describe("local agent evaluation entry", () => {
  it("keeps the prepared Nova link on the real agent and its tool-contract dataset", () => {
    const params = new URL(NOVA_AGENT_EVALUATION_HREF, "http://example.test").searchParams;
    expect(Object.fromEntries(params)).toEqual({ type: "agent", agent: "local:nova-refunds", dataset: "agent_nova_refunds_v1" });
    expect(NOVA_AGENT_DEMO.metrics).toEqual(["agent.tool_call_accuracy", "agent.tool_selection", "agent.tool_input_accuracy"]);
  });
  it("uses the runnable logical agent reference and its own golden dataset", () => {
    const url = new URL(agentEvaluationHref(target), "http://example.test");
    expect(url.pathname).toBe("/evaluate");
    expect(Object.fromEntries(url.searchParams)).toEqual({ type: "agent", agent: "local:nova-refunds", dataset: "agent_nova_refunds_v1" });
  });

  it("does not infer a local agent from a name or environment", () => {
    expect(isLocalWorkflowAgent(target)).toBe(true);
    expect(isLocalWorkflowAgent({ ...target, environment: "local", configuration: {} })).toBe(false);
  });

  it("does not inject unavailable or unknown recommended checks", () => {
    const agent = { recommended_metric_ids: ["tool.call", "judge.hidden", "missing"] } as AgentSummary;
    expect(runnableAgentMetricIds(agent, [{ metric_id: "tool.call" }, { metric_id: "judge.hidden", available_in_run: false }])).toEqual(["tool.call"]);
  });

  it("guards malformed external metadata", () => {
    expect(localAgentStrings({ ...target, configuration: { tools: [null, "lookup", 7] } }, "tools")).toEqual(["lookup"]);
    expect(localAgentStrings({ ...target, configuration: { tools: "lookup" } }, "tools")).toEqual([]);
  });
});


describe("agent evaluation naming", () => {
  const previous = { name: "Nova refunds", display_name: "Nova refunds" } as AgentSummary;
  const next = { name: "Course advisor", display_name: "Course advisor" } as AgentSummary;
  it("keeps autogenerated names aligned with a manually changed agent", () => {
    expect(nameAfterAgentChange("Nova refunds · baseline", previous, next)).toBe("Course advisor · baseline");
  });
  it("preserves names the presenter has edited", () => {
    expect(nameAfterAgentChange("My live class demo", previous, next)).toBe("My live class demo");
    expect(nameAfterAgentChange("My live class demo", null, next)).toBe("My live class demo");
  });
});
