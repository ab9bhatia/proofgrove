import type { DatasetRecord } from "@/lib/api";
import { recordMetadata, recordToCsvRow } from "@/lib/dataset-csv";
import { metadataLabel, metadataValueText } from "@/components/dataset-record-metadata";

/** Presentation only: CSV export retains its original response-in-Metadata contract. */
export function datasetPreviewRow(record: DatasetRecord, index: number) {
  const row = recordToCsvRow(record, index);
  const containers = [record.expectations ?? {}, record.inputs ?? {}];
  // Use the scoring source's precedence; never borrow the expected answer.
  const nonempty = containers.find((source) => Boolean(source.response) || source.response === 0);
  const declared = nonempty ?? containers.find((source) => Object.hasOwn(source, "response") && source.response != null);
  const value = declared?.response;
  const response = !declared ? null : typeof value === "string" ? value : JSON.stringify(value);
  const metadata = recordMetadata(record);
  if (declared) delete metadata.response;
  const authored = record.tags?.evidence === "authored-response" || record.tags?.provenance?.startsWith("authored-");
  return { ...row, metadata, response, authored: Boolean(authored), responseIsText: typeof value === "string" };
}

export function DatasetEvidenceGuide({ supplied = false }: { supplied?: boolean }) {
  return (
    <div className="rounded-lg border bg-muted/25 px-4 py-3 text-sm leading-6">
      <p><strong>Before a live run:</strong> prepare inputs, reviewed expected outputs and metadata tags. These form the golden dataset.</p>
      <p className="mt-1 text-muted-foreground"><strong className="font-medium text-foreground">During the run:</strong> the model or agent generates an actual response. The run report shows that response beside the reference and its scores.</p>
      {supplied ? <p className="mt-2 text-xs leading-5 text-muted-foreground">This dataset also stores supplied responses, shown separately below. Existing-response evaluations score these stored answers. A live model or agent evaluation generates fresh answers instead. Raw JSON and CSV retain the original storage layout.</p> : null}
    </div>
  );
}

export function SuppliedResponse({ row }: { row: ReturnType<typeof datasetPreviewRow> }) {
  if (row.response == null) return <span className="text-muted-foreground">No supplied response</span>;
  return <>
    <span className="mb-2 block text-[11px] font-medium text-muted-foreground">{row.authored ? "Authored example · not a live result" : "Stored answer · not generated by this run"}</span>
    {row.response || <span className="italic text-muted-foreground">Empty response</span>}
    {!row.responseIsText ? <span className="mt-2 block text-xs text-destructive">Stored value is not a text response.</span> : null}
  </>;
}

export function DatasetPreviewTable({ records }: { records: DatasetRecord[] }) {
  const rows = records.map(datasetPreviewRow);
  const supplied = rows.some((row) => row.response != null);
  return (
    <div className="space-y-4">
      <DatasetEvidenceGuide supplied={supplied} />
      <div role="region" aria-label="Dataset preview rows" tabIndex={0} className="overflow-x-auto rounded-lg border bg-background focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring">
        <table className={`w-full table-fixed text-sm ${supplied ? "min-w-[62rem]" : "min-w-[46rem]"}`}>
          <caption className="sr-only">Inputs, expected reference answers and metadata prepared before evaluation{supplied ? ", with supplied responses kept separate" : ""}</caption>
          <colgroup>
            <col className="w-[6%]" />
            <col className={supplied ? "w-[23%]" : "w-[30%]"} />
            <col className={supplied ? "w-[24%]" : "w-[34%]"} />
            {supplied ? <col className="w-[25%]" /> : null}
            <col className={supplied ? "w-[22%]" : "w-[30%]"} />
          </colgroup>
          <thead>
            <tr className="border-b bg-muted/50 text-xs text-muted-foreground">
              <th scope="col" className="px-3 py-3 text-left font-medium">Row</th>
              <th scope="col" className="px-3 py-3 text-left font-medium">Input / question</th>
              <th scope="col" className="px-3 py-3 text-left font-medium">Expected output / reference</th>
              {supplied ? <th scope="col" className="px-3 py-3 text-left font-medium">Supplied response</th> : null}
              <th scope="col" className="px-3 py-3 text-left font-medium">Metadata / tags</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((row, index) => <tr key={records[index]?.dataset_record_id ?? index} className="border-b align-top last:border-b-0">
              <td className="px-3 py-3 font-mono text-xs text-muted-foreground">{row.serialNo}</td>
              <td className="break-words px-3 py-3 whitespace-pre-wrap">{row.question || "—"}</td>
              <td className="break-words px-3 py-3 whitespace-pre-wrap">{row.expectedOutput || "No reference provided"}</td>
              {supplied ? <td className="break-words px-3 py-3 whitespace-pre-wrap">
                <SuppliedResponse row={row} />
              </td> : null}
              <td className="break-words px-3 py-3">
                {Object.keys(row.metadata).length ? <dl className="space-y-2 text-xs leading-5">
                  {Object.entries(row.metadata).map(([key, value]) => <div key={key}>
                    <dt className="font-medium text-muted-foreground">{metadataLabel(key)}</dt>
                    <dd className="whitespace-pre-wrap break-words">{metadataValueText(key, value)}</dd>
                  </div>)}
                </dl> : <span className="text-xs text-muted-foreground">No metadata tags</span>}
              </td>
            </tr>)}
          </tbody>
        </table>
      </div>
    </div>
  );
}
